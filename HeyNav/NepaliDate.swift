    static func from(adDate: Date) -> NepaliDate? {
        let calendar = Calendar(identifier: .gregorian)
        guard let epoch = calendar.date(from: DateComponents(year: 1943, month: 4, day: 14)) else {
            return nil
        }
        let startOfEpoch = calendar.startOfDay(for: epoch)
        let startOfInput = calendar.startOfDay(for: adDate)

        guard let daysSinceEpoch = calendar.dateComponents([.day], from: startOfEpoch, to: startOfInput).day,
              daysSinceEpoch >= 0 else {
            return nil
        }

        var remaining = daysSinceEpoch
        var bsYear = 2000
        var rowIndex = 0

        while rowIndex < calendarData.count {
            let totalDaysInYear = calendarData[rowIndex][13]
            if remaining < totalDaysInYear {
                break
            }
            remaining -= totalDaysInYear
            bsYear += 1
            rowIndex += 1
        }

        guard rowIndex < calendarData.count else {
            return nil
        }

        let row = calendarData[rowIndex]
        var bsMonth = 1
        var monthIndex = 1

        while monthIndex <= 12 {
            let daysInMonth = row[monthIndex]
            if remaining < daysInMonth {
                break
            }
            remaining -= daysInMonth
            bsMonth += 1
            monthIndex += 1
        }

        let bsDay = remaining + 1
        return NepaliDate(year: bsYear, month: bsMonth, day: bsDay)
    }

    func formatted(style: DateStyle) -> String {
        guard (1...12).contains(month) else { return "—" }

        let english = Self.monthNamesEnglish[month - 1]
        let nepali = Self.monthNamesNepali[month - 1]

        switch style {
        case .englishNumeric:
            return "\(year)-\(String(format: "%02d", month))-\(String(format: "%02d", day))"
        case .nepaliNumeric:
            return "\(Self.devanagari(year))-\(Self.devanagari(month, padded: true))-\(Self.devanagari(day, padded: true))"
        case .englishNamed:
            return "\(year) \(english) \(day)"
        case .englishNamedDayFirst:
            return "\(day) \(english) \(year)"
        case .englishNamedShort:
            return "\(english) \(day)"
        case .nepaliNamed:
            return "\(Self.devanagari(year)) \(nepali) \(Self.devanagari(day))"
        case .nepaliNamedDayFirst:
            return "\(Self.devanagari(day)) \(nepali) \(Self.devanagari(year))"
        case .nepaliNamedShort:
            return "\(nepali) \(Self.devanagari(day))"
        }
    }

    private static let devanagariDigits: [Character: Character] = [
        "0": "०", "1": "१", "2": "२", "3": "३", "4": "४",
        "5": "५", "6": "६", "7": "७", "8": "८", "9": "९"
    ]

    private static func devanagari(_ value: Int, padded: Bool = false) -> String {
        let raw = padded ? String(format: "%02d", value) : String(value)
        return String(raw.map { devanagariDigits[$0] ?? $0 })
    }
